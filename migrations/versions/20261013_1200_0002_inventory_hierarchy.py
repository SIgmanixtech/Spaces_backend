"""inventory hierarchy: spaces on floors, with parent and child spaces

Revision ID: 0002
Revises: 0001
Create Date: 2026-10-13 12:00:00.000000+00:00

Additive. No existing row is rewritten, and no building, floor or space is
created: every space that exists today stays exactly as it is and becomes an
"unassigned" space (no floor, no parent, depth 0), which the new constraints
explicitly allow. Assigning it to a floor is an administrator's decision made
later through the API, not something this migration guesses.

Hand-written, not autogenerated, so that it needs no database connection to
prepare. tests/test_migrations.py checks it against the models.

Nothing here belongs to the allocation engine: no claims, no locking or guard
triggers. Those are a later, separately approved revision.
"""

from collections.abc import Sequence

import sqlalchemy as sa
from alembic import op

revision: str = '0002'
down_revision: str | None = '0001'
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None


LEGACY_SPACE_TYPES = "'DESK', 'PRIVATE_OFFICE', 'CABIN', 'MEETING_ROOM', 'COWORKING'"
NEW_SPACE_TYPES = "'FLOOR', 'PORTION', 'CONFERENCE_ROOM', 'TRAINING_ROOM', 'NON_RENTABLE'"


def upgrade() -> None:
    # 1. Columns. Every default describes an unassigned, rentable space, so the
    #    constraints added below already hold for all existing rows.
    op.add_column('spaces', sa.Column('building_id', sa.Uuid(), nullable=True))
    op.add_column('spaces', sa.Column('floor_id', sa.Uuid(), nullable=True))
    op.add_column('spaces', sa.Column('parent_space_id', sa.Uuid(), nullable=True))
    op.add_column('spaces', sa.Column('depth', sa.SmallInteger(), server_default='0', nullable=False))
    op.add_column('spaces', sa.Column('parent_depth', sa.SmallInteger(), nullable=True))
    op.add_column('spaces', sa.Column('area_sqft', sa.Numeric(precision=12, scale=2), nullable=True))
    op.add_column('spaces', sa.Column('is_rentable', sa.Boolean(), server_default=sa.text('true'), nullable=False))

    # 2. Space types: the allowed list only grows, so no existing value is rejected.
    op.drop_constraint(op.f('ck_spaces_space_type_valid'), 'spaces', type_='check')
    op.create_check_constraint(
        op.f('ck_spaces_space_type_valid'), 'spaces',
        f"space_type IN ({LEGACY_SPACE_TYPES}, {NEW_SPACE_TYPES})",
    )

    # 3. Row-level rules.
    op.create_check_constraint(op.f('ck_spaces_area_sqft_positive'), 'spaces', 'area_sqft > 0')
    op.create_check_constraint(
        op.f('ck_spaces_non_rentable'), 'spaces', "space_type <> 'NON_RENTABLE' OR NOT is_rentable"
    )
    op.create_check_constraint(
        op.f('ck_spaces_floor_building_pair'), 'spaces', '(floor_id IS NULL) = (building_id IS NULL)'
    )
    op.create_check_constraint(
        op.f('ck_spaces_parent_depth_pair'), 'spaces',
        '(parent_space_id IS NULL) = (parent_depth IS NULL)',
    )
    op.create_check_constraint(
        op.f('ck_spaces_depth_valid'), 'spaces',
        'depth BETWEEN 0 AND 4 AND (parent_depth IS NULL OR parent_depth = depth - 1)',
    )
    # Either unassigned (the only shape existing rows have), or on a floor where
    # the FLOOR space is the root and every other space has a parent.
    op.create_check_constraint(
        op.f('ck_spaces_hierarchy_shape'), 'spaces',
        "(floor_id IS NULL AND parent_space_id IS NULL AND depth = 0 AND space_type <> 'FLOOR')"
        " OR (floor_id IS NOT NULL"
        " AND (space_type = 'FLOOR') = (parent_space_id IS NULL)"
        " AND (space_type = 'FLOOR') = (depth = 0))",
    )

    # 4. Same-property chain: space -> floor -> building -> property.
    op.create_foreign_key(
        op.f('fk_spaces_building_id_buildings'), 'spaces', 'buildings',
        ['building_id', 'property_id'], ['id', 'property_id'], ondelete='RESTRICT',
    )
    op.create_foreign_key(
        op.f('fk_spaces_floor_id_floors'), 'spaces', 'floors',
        ['floor_id', 'building_id'], ['id', 'building_id'], ondelete='RESTRICT',
    )

    # 5. Parent on the same floor, exactly one level up. Deferred so a subtree
    #    can be moved within one transaction.
    op.create_unique_constraint('uq_spaces_id_floor_depth', 'spaces', ['id', 'floor_id', 'depth'])
    op.create_foreign_key(
        op.f('fk_spaces_parent_space_id_spaces'), 'spaces', 'spaces',
        ['parent_space_id', 'floor_id', 'parent_depth'], ['id', 'floor_id', 'depth'],
        ondelete='RESTRICT', deferrable=True, initially='DEFERRED',
    )

    # 6. Indexes.
    op.create_index(op.f('ix_spaces_building_id'), 'spaces', ['building_id'], unique=False)
    op.create_index(op.f('ix_spaces_floor_id'), 'spaces', ['floor_id'], unique=False)
    op.create_index(op.f('ix_spaces_parent_space_id'), 'spaces', ['parent_space_id'], unique=False)
    op.create_index(
        'uq_spaces_floor_root', 'spaces', ['floor_id'], unique=True,
        postgresql_where=sa.text("space_type = 'FLOOR' AND archived_at IS NULL"),
    )


